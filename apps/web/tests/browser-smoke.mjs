import assert from 'node:assert/strict';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';
import { api, agentOnline, DeviceClient, newKeyPair, registerUser, startGateway, waitFor } from '../../gateway/tests/support.mjs';

const playwrightPath = process.env.RAB_PLAYWRIGHT_MODULE;
const { chromium } = await import(playwrightPath ? pathToFileURL(playwrightPath).href : 'playwright');
const gateway = await startGateway({ cwd: tmpdir() });
const deviceId = 'browser-test-device';
const keyPair = newKeyPair();
const credentials = { email: 'browser-test@test.local', password: 'password123' };
let first;
let agent;
let browser;

try {
  const ownerToken = await registerUser(gateway.base, credentials.email);
  first = await new DeviceClient(gateway.wsUrl, { deviceId, keyPair, receipts: true }).connect();
  await first.handshake({ localProof: gateway.setupToken });
  await waitFor(() => agentOnline(gateway, deviceId));
  const renewed = await api(gateway.base, '/api/setup/pairing/renew', { method: 'POST', setupToken: gateway.setupToken });
  assert.equal(renewed.status, 200);
  browser = await chromium.launch({ executablePath: process.env.RAB_CHROMIUM_EXECUTABLE || undefined, headless: true });
  const page = await browser.newPage({ viewport: { width: 360, height: 740 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const state = label => page.getByRole('heading', { name: label, exact: true });

  const index = await page.goto(gateway.base);
  assert.match(index.headers()['content-security-policy'], /default-src 'self'/);
  assert.doesNotMatch(index.headers()['content-security-policy'], /unsafe-inline/);
  await page.getByLabel('邮箱').fill(credentials.email);
  await page.getByLabel('密码').fill(credentials.password);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByRole('button', { name: '绑定电脑', exact: true }).click();
  await page.getByLabel('6 位配对码').fill(renewed.data.code === '000000' ? '000001' : '000000');
  await page.getByRole('button', { name: '确认绑定', exact: true }).click();
  await page.getByText('配对码不正确或已过期，请在电脑上重新生成。').waitFor();
  await page.getByLabel('6 位配对码').fill(renewed.data.code);
  await page.getByRole('button', { name: '确认绑定', exact: true }).click();
  await first.waitFor('device.bound');
  first.close();
  agent = await new DeviceClient(gateway.wsUrl, { deviceId, keyPair, receipts: true }).connect();
  await agent.handshake();
  await agent.waitFor('agent.ready');
  await page.locator('#deviceText').getByText('电脑在线').waitFor();
  await page.getByRole('button', { name: '新建会话', exact: true }).click();
  await state('开始这次会话').waitFor();
  const token = await page.evaluate(() => sessionStorage.getItem('rab_token'));
  assert.equal(typeof token, 'string');
  assert.notEqual(token, ownerToken, 'browser login issued a new token');
  const request = (path, init) => api(gateway.base, path, { token, ...init });
  const session = (await request('/api/sessions')).data[0];
  assert.equal(session.provider_id, 'local');

  const before = await request('/api/tasks', { method: 'POST', body: { task_id: 'browser-held', session_id: session.id, kind: 'shell', input: '仅用于验证确认卡的测试内容' } });
  assert.equal(before.data.state, 'awaiting_confirmation');
  await page.reload();
  await state('等待你确认').waitFor();
  await page.getByText('仅用于验证确认卡的测试内容', { exact: true }).waitFor();
  await page.getByRole('button', { name: '拒绝', exact: true }).click();
  await state('已取消').waitFor();
  assert.equal(agent.tasks.length, 0);

  const second = await request('/api/sessions', { method: 'POST', body: { provider_id: 'local', title: '第二个会话' } });
  assert.equal(second.status, 200);
  await page.getByRole('button', { name: '打开会话和账户菜单', exact: true }).click();
  await page.getByRole('button', { name: '第二个会话 local', exact: true }).click();
  await state('第二个会话').waitFor();
  await state('开始这次会话').waitFor();
  assert.equal(await page.locator('#openSidebar').getAttribute('aria-expanded'), 'false');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  const posted = [];
  await page.route('**/api/tasks', async route => {
    if (route.request().method() !== 'POST') return route.continue();
    posted.push(route.request().postDataJSON());
    if (posted.length === 1) return route.abort('connectionreset');
    return route.continue();
  });
  await page.getByLabel('告诉电脑要做什么').fill('现在几点');
  await page.getByRole('button', { name: '发送', exact: false }).click();
  await page.getByText('有一条提交尚未收到回执').waitFor();
  await page.reload();
  await page.getByRole('button', { name: '用原任务编号重试' }).click();
  await state('电脑已接单 · 排队中').waitFor();
  assert.equal(posted.length, 2);
  assert.deepEqual(posted[1], posted[0]);
  assert.equal(posted[0].session_id, second.data.session.id);
  const task = await waitFor(() => agent.tasks.find(item => item.task_id === posted[0].task_id));
  await page.getByRole('button', { name: '请求取消', exact: true }).click();
  await agent.waitFor('agent.task.cancel');
  await state('已请求取消 · 等待确认').waitFor();
  agent.report(task, 'cancelled', '电脑确认任务未开始', 2);
  await state('已取消').waitFor();

  await page.unroute('**/api/tasks');
  let lostResponseCount = 0;
  await page.route('**/api/tasks', async route => {
    if (route.request().method() !== 'POST') return route.continue();
    lostResponseCount += 1;
    const accepted = await route.fetch();
    assert.equal(accepted.status(), 200);
    await route.abort('connectionreset');
  });
  await page.getByLabel('告诉电脑要做什么').fill('系统信息');
  await page.getByRole('button', { name: '发送', exact: false }).click();
  const successful = await waitFor(() => agent.tasks.find(item => item.input === '系统信息'));
  agent.report(successful, 'succeeded', '浏览器夹具的唯一结果', 2);
  await page.getByText('浏览器夹具的唯一结果', { exact: false }).waitFor();
  await page.locator('#pendingSubmission').waitFor({ state: 'hidden' });
  await page.reload();
  await state('已完成').waitFor();
  assert.equal(await page.getByText('浏览器夹具的唯一结果', { exact: false }).count(), 1);
  assert.equal(agent.tasks.length, 2);
  assert.equal(lostResponseCount, 1);
  await page.getByRole('button', { name: '打开会话和账户菜单', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '解除电脑绑定', exact: true }).click();
  await page.getByText('已解除绑定。会话历史仍可查看。').waitFor();
  assert.equal((await agent.closed).reason, 'device_revoked');
  assert.equal((await request('/api/dashboard')).data.device.status, 'unpaired');
  assert.equal(await page.getByText('浏览器夹具的唯一结果', { exact: false }).count(), 1);
  assert.deepEqual(errors, []);
  console.log('Chromium 360px: login, pairing retry, reload, session switching, same-ID retry, cancellation, result recovery and revocation OK');
} finally {
  await browser?.close();
  first?.close();
  agent?.close();
  await gateway.stop();
}
